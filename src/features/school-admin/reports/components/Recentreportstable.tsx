import type { GeneratedReport } from "../types/reports.types";
import { FileText, Download, Inbox } from "lucide-react";
import { Button } from "@/components/ui/button";

const ReportIcon = ({ type }: { type: GeneratedReport["type"] }) => {
  const color: Record<string, string> = {
    ATTENDANCE: "text-indigo-500 bg-indigo-50",
    FEE_COLLECTION: "text-emerald-500 bg-emerald-50",
    STUDENT: "text-blue-500 bg-blue-50",
    WHATSAPP_ACTIVITY: "text-green-500 bg-green-50",
    ADMISSIONS: "text-violet-500 bg-violet-50",
    STAFF: "text-amber-500 bg-amber-50",
  };
  return (
    <div className={`w-9 h-9 rounded-lg flex items-center justify-center ${color[type] ?? "text-gray-500 bg-gray-50"}`}>
      <FileText className="w-4 h-4" />
    </div>
  );
};

interface RecentReportsTableProps {
  reports: GeneratedReport[];
  onDownload: (id: string) => void;
}

const RecentReportsTable = ({ reports, onDownload }: RecentReportsTableProps) => {
  if (reports.length === 0) {
    return (
      <div className="bg-white rounded-xl border border-gray-100 shadow-sm p-12 flex flex-col items-center justify-center text-center">
        <div className="w-16 h-16 rounded-full bg-gray-50 flex items-center justify-center mb-4">
          <Inbox className="w-8 h-8 text-gray-300" />
        </div>
        <h3 className="text-lg font-semibold text-gray-900">No reports generated yet</h3>
        <p className="text-sm text-gray-500 mt-1">Generate your first report from the cards above</p>
      </div>
    );
  }

  return (
    <div className="bg-white rounded-xl border border-gray-100 shadow-sm overflow-hidden">
      <div className="overflow-x-auto">
        <table className="w-full">
          <thead>
            <tr className="border-b border-gray-100 bg-gray-50">
              {["Report Name", "Generated On", "Period", "Format", "Generated By", "Download"].map((label) => (
                <th
                  key={label}
                  className="px-5 py-3.5 text-left text-xs font-semibold uppercase tracking-wider text-gray-500"
                >
                  {label}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {reports.map((report, i) => (
              <tr
                key={report.id}
                className={`border-b border-gray-50 transition-colors hover:bg-gray-100 ${
                  i % 2 === 1 ? "bg-gray-50" : "bg-white"
                }`}
              >
                <td className="px-5 py-4">
                  <div className="flex items-center gap-3">
                    <ReportIcon type={report.type} />
                    <span className="text-sm font-medium text-gray-900">{report.reportName}</span>
                  </div>
                </td>
                <td className="px-5 py-4 text-sm text-gray-600 whitespace-nowrap">{report.generatedOn}</td>
                <td className="px-5 py-4 text-sm text-gray-600">{report.period}</td>
                <td className="px-5 py-4">
                  <span className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-bold uppercase tracking-wider ${
                    report.format === "PDF" ? "text-red-600 bg-red-50" : "text-emerald-600 bg-emerald-50"
                  }`}>
                    {report.format}
                  </span>
                </td>
                <td className="px-5 py-4">
                  <div className="flex items-center gap-2">
                    <div className="w-7 h-7 rounded-full bg-indigo-100 flex items-center justify-center text-[10px] font-bold text-indigo-700">
                      {report.generatedBy?.initials ?? "?"}
                    </div>
                    <span className="text-sm text-gray-600">{report.generatedBy?.name ?? "Unknown"}</span>
                  </div>
                </td>
                <td className="px-5 py-4">
                  <Button
                    type="button"
                    variant="ghost"
                    size="sm"
                    onClick={() => onDownload(report.id)}
                    className="w-9 h-9 rounded-lg border border-gray-200 text-gray-500 hover:text-indigo-600 hover:border-indigo-300 hover:bg-indigo-50 transition-all p-0"
                  >
                    <Download className="w-4 h-4" />
                  </Button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <div className="px-5 py-3 border-t border-gray-100 flex justify-end">
        <button className="text-xs font-semibold text-indigo-600 hover:text-indigo-800 transition-colors">
          View All History →
        </button>
      </div>
    </div>
  );
};

export default RecentReportsTable;
